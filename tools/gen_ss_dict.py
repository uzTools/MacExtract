#!/usr/bin/env python3
"""gen_ss_dict.py — SpaceSaver's preset dictionaries into src/ss_dict.h.

SpaceSaver's LZSS starts with its window loaded from a table that ships
inside SpaceSaver itself, and a file cannot be decoded without the exact
bytes of it (FORMATS.md, "StuffIt SpaceSaver"). The fork record's byte at
+12 says which one: index 0 is `PrAm` -4048, 9,679 bytes, and index 1 is
`PrAm` -4047, which is four spaces.

    tools/vmac/spacesaver.py --layout      # writes the resources out
    tools/gen_ss_dict.py                   # then this

The output is COMMITTED, so the build depends on neither the emulator nor
a copy of SpaceSaver. The table is Aladdin Systems' — see NOTICE, and
DECISIONS.md 2026-08-23 for the decision to carry it.

Usage: tools/gen_ss_dict.py [DIR]
   DIR defaults to the emulator's specimen directory, where --layout puts
   PrAm-4048.bin and PrAm-4047.bin.
"""
import hashlib
import os
import sys

DEFAULT = os.path.expanduser(
    "~/.cache/unclassic/vmac/specimens/spacesaver")
DST = "src/ss_dict.h"

HEAD = '''/*
 * ss_dict.h — StuffIt SpaceSaver's preset dictionaries.
 *
 * GENERATED by tools/gen_ss_dict.py from the `PrAm` resources of an
 * installed SpaceSaver. Do not edit by hand; regenerate instead.
 *
 * These bytes are **Copyright (c) 1993 Aladdin Systems, Inc.** and are
 * carried here so that a SpaceSaver-compressed file can be read at all:
 * its LZSS window starts loaded with them, so a decoder without them
 * produces wrong output rather than no output. See NOTICE, and
 * DECISIONS.md 2026-08-23 (the dictionary) for the decision and who
 * took it. They are data required for interoperability, not part of
 * this project's LGPL source.
 *
 * The fork record's byte at +12 selects one: 0 is `PrAm` -4048 and 1 is
 * `PrAm` -4047. Everything SpaceSaver writes uses 0.
 *
 * `ss_m2_default` is the third table and the smallest: method 2 fills
 * 4,096 dictionary entries with a pointer to `CMod 4`'s own last
 * eighteen bytes, so a code whose entry was never filled copies THOSE —
 * and the compressor does emit such codes.
 */
#ifndef UNC_SS_DICT_H
#define UNC_SS_DICT_H

#include <stdint.h>

'''

TAIL = '''
#endif /* UNC_SS_DICT_H */
'''


def emit(out, name, rid, data):
    out.append("/* 'PrAm' %d, %d bytes, sha256 %s */"
               % (rid, len(data), hashlib.sha256(data).hexdigest()[:32]))
    out.append("#define %s_LEN %du" % (name.upper(), len(data)))
    out.append("static const uint8_t %s[%d] = {" % (name, len(data)))
    for i in range(0, len(data), 12):
        row = ", ".join("0x%02x" % b for b in data[i:i + 12])
        out.append("    %s," % row)
    out.append("};")
    out.append("")


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    files = [("ss_dict0", -4048, os.path.join(src, "PrAm-4048.bin")),
             ("ss_dict1", -4047, os.path.join(src, "PrAm-4047.bin"))]
    m2 = os.path.join(src, "CMod4.bin")
    for _, _rid, p in files:
        if not os.path.exists(p):
            sys.exit("gen_ss_dict: %s not found — run "
                     "tools/vmac/spacesaver.py --layout first" % p)
    out = [HEAD.rstrip("\n"), ""]
    for name, rid, p in files:
        with open(p, "rb") as f:
            emit(out, name, rid, f.read())
    if os.path.exists(m2):
        with open(m2, "rb") as f:
            tail = f.read()[-18:]
        out.append("/* `CMod 4`'s last 18 bytes: what an unfilled method 2 "
                   "dictionary entry")
        out.append(" * points at (@0x6fc fills the table with it). sha256 %s */"
                   % hashlib.sha256(tail).hexdigest()[:32])
        out.append("#define SS_M2_DEFAULT_LEN %du" % len(tail))
        out.append("static const uint8_t ss_m2_default[%d] = {" % len(tail))
        for i in range(0, len(tail), 12):
            out.append("    %s," % ", ".join("0x%02x" % b
                                             for b in tail[i:i + 12]))
        out.append("};")
        out.append("")
    else:
        sys.exit("gen_ss_dict: %s not found — run "
                 "tools/vmac/spacesaver.py --layout first" % m2)
    out.append(TAIL.strip("\n"))
    with open(DST, "w") as f:
        f.write("\n".join(out) + "\n")
    print("gen_ss_dict: wrote %s" % DST)
    return 0


if __name__ == "__main__":
    sys.exit(main())
