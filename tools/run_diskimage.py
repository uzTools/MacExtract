#!/usr/bin/env python3
"""run_diskimage.py — the disk-image probe, graded by deark.

Disk images stay out by the brief, so what is tested here is one thing:
`unclassic sniff` says "disk image" for a volume, and says something else
for everything that is not one. The probe reads four structures, and each
is generated by something other than this project and confirmed by an
implementation other than this project:

  ISO 9660, 2048-byte sectors  written by pycdlib (reference/pycdlib),
                               confirmed by deark AND by `lsar`
  the three raw CD layouts     the same image re-blocked to 2336+8,
                               2352+16 and 2352+24, which are deark's own
                               `cdraw_detect_params`; confirmed by deark
  HFS                          written by hformat (hfsutils), confirmed
                               by deark
  Apple Partition Map          built here from the field offsets deark's
                               apm module parses, confirmed by deark

HFS+/HFSX is the one branch with no oracle and no specimen: deark reads
those two signatures but parses no further, nothing on this machine
writes an HFS+ volume, and every HFS+ volume Mac OS 8.1-9 makes is inside
an HFS wrapper, so it is the HFS branch that claims it (FORMATS.md, "Disk
images"). The cases below are hand-built and say so.

The negatives matter as much: each branch is re-run with its
corroborating field spoiled, and the whole fixture corpus is swept, since
a probe that claims an archive is worse than one that claims nothing.

Skips cleanly, and says which part it skipped, when hfsutils, deark or
reference/pycdlib is missing.
"""
import os
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
PYCDLIB = os.path.join(ROOT, "reference", "pycdlib")


def build(script, binary):
    path = os.path.abspath(os.path.join(ROOT, binary))
    if os.path.exists(path):
        return path
    r = subprocess.run(["sh", os.path.join(ROOT, "tools", script)],
                       capture_output=True)
    return path if r.returncode == 0 and os.path.exists(path) else None


def sniff(unclassic, path):
    r = subprocess.run([unclassic, "sniff", path], capture_output=True,
                       text=True)
    return r.stdout.strip()


def deark_module(deark, path):
    """The module deark identifies the file as, or "" for none. `-l` lists
    what it would extract and prints `Module: <id>` first."""
    r = subprocess.run([deark, "-l", path], capture_output=True, text=True)
    for line in r.stdout.split("\n"):
        if line.startswith("Module: "):
            return line[len("Module: "):].strip()
    return ""


def make_iso(dest):
    """A real ISO 9660 image, written by pycdlib. Returns False when
    reference/pycdlib is not there."""
    if not os.path.isdir(PYCDLIB):
        return False
    sys.path.insert(0, PYCDLIB)
    try:
        import pycdlib
    except ImportError:
        return False
    finally:
        sys.path.pop(0)
    import io
    iso = pycdlib.PyCdlib()
    iso.new(interchange_level=1, vol_ident="UNCLASSIC")
    body = b"a file on a CD\n" * 64
    iso.add_fp(io.BytesIO(body), len(body), "/HELLO.TXT;1")
    iso.write(dest)
    iso.close()
    return True


def reblock(src, dest, total, offset):
    """Re-block a 2048-byte-sector image into one of the raw CD layouts:
    `total` bytes per sector with the user data `offset` bytes in. Source:
    cdraw_detect_params() in reference/deark/modules/iso9660.c."""
    raw = open(src, "rb").read()
    out = bytearray()
    for i in range(0, len(raw), 2048):
        sector = bytearray(total)
        sector[offset:offset + 2048] = raw[i:i + 2048].ljust(2048, b"\0")
        out += sector
    open(dest, "wb").write(bytes(out))


def make_hfs(dest, kb, name="Test"):
    """An HFS volume, formatted by hfsutils. Returns False without it."""
    if not shutil.which("hformat"):
        return False
    with open(dest, "wb") as f:
        f.truncate(kb * 1024)
    r = subprocess.run(["hformat", "-l", name, dest], capture_output=True)
    return r.returncode == 0


def make_apm(dest, blocks=2048):
    """An Apple Partition Map: a driver descriptor record, the map's own
    entry and one Apple_HFS entry. Field offsets: do_partition() and
    de_run_apm() in reference/deark/modules/apm.c (signature, then the
    partition count, start block and block count as big-endian longs at
    4, 8 and 12, the 32-byte name at 16 and the 32-byte type at 48)."""
    blk = 512
    img = bytearray(blocks * blk)
    # Block 0: driver descriptor record, "ER" + block size + block count.
    struct.pack_into(">2sHI", img, 0, b"ER", blk, blocks)

    def entry(at, start, size, name, ptype):
        struct.pack_into(">2sHIII", img, at, b"PM", 0, 2, start, size)
        img[at + 16:at + 16 + len(name)] = name
        img[at + 48:at + 48 + len(ptype)] = ptype

    entry(blk, 1, 63, b"Apple", b"Apple_partition_map")
    entry(2 * blk, 64, blocks - 64, b"untitled", b"Apple_HFS")
    open(dest, "wb").write(bytes(img))


def make_volume_header(dest, sig, size=4096, alblksiz=8192):
    """A block at 1024 with a volume signature in it, and nothing else:
    what the probe reads for HFS ("BD" plus its allocation block size) and
    for HFS+/HFSX ("H+"/"HX"). Hand-built — see the module docstring."""
    img = bytearray(size)
    img[1024:1026] = sig
    if sig == b"BD":
        struct.pack_into(">I", img, 1024 + 20, alblksiz)
    open(dest, "wb").write(bytes(img))


def main():
    unclassic = os.path.join(ROOT, "build", "unclassic")
    args = sys.argv[1:]
    if "--unclassic" in args:
        unclassic = args[args.index("--unclassic") + 1]
    if not os.path.exists(unclassic):
        print("run_diskimage: no CLI at %s" % unclassic)
        return 1

    deark = build("build_deark.sh", "build/deark/deark")
    if not deark:
        print("run_diskimage: SKIPPED — no reference/deark "
              "(tools/fetch_references.sh)")
        return 0

    problems, ran, skipped = [], 0, []
    tmp = tempfile.mkdtemp()

    def check(label, cond, detail=""):
        nonlocal ran
        ran += 1
        if not cond:
            problems.append("%s: %s" % (label, detail or "failed"))

    def is_image(label, path, want_module=None):
        """The claim, both ways round: we name it, and where deark has a
        module for the format, deark names it too."""
        got = sniff(unclassic, path)
        check(label, got == "disk image", "sniffed as %r" % got)
        if want_module:
            mod = deark_module(deark, path)
            check(label + " (deark)", mod == want_module,
                  "deark says %r, not %r" % (mod, want_module))

    def not_image(label, path):
        got = sniff(unclassic, path)
        check(label, got != "disk image", "claimed as a disk image")

    try:
        # ------------------------------------------------------ #
        # ISO 9660, in all four sector layouts                    #
        # ------------------------------------------------------ #
        iso = os.path.join(tmp, "cd.iso")
        if make_iso(iso):
            is_image("ISO 9660 (2048-byte sectors)", iso, "iso9660")
            # ...and the oracle this project uses everywhere else, which
            # does read ISO 9660 (XADISO9660Parser.m).
            if shutil.which("lsar"):
                r = subprocess.run(["lsar", iso], capture_output=True,
                                   text=True)
                check("ISO 9660 (lsar)", "ISO 9660" in r.stdout,
                      "lsar says %r" % r.stdout.split("\n")[0])
            for total, off, name in ((2336, 8, "raw2336"),
                                     (2352, 16, "raw2352a"),
                                     (2352, 24, "raw2352b")):
                p = os.path.join(tmp, name + ".bin")
                reblock(iso, p, total, off)
                is_image("raw CD image (%d-byte sectors, +%d)" % (total, off),
                         p, "cd_raw")
            # A descriptor at sector 16 and nothing at sector 17 is not an
            # image: one five-character string may occur in anything.
            half = os.path.join(tmp, "half.iso")
            raw = bytearray(open(iso, "rb").read())
            raw[2048 * 17:2048 * 17 + 8] = bytes(8)
            open(half, "wb").write(bytes(raw))
            not_image("one CD descriptor only", half)
        else:
            skipped.append("ISO 9660 (no reference/pycdlib)")

        # ------------------------------------------------------ #
        # HFS, as hfsutils writes it                              #
        # ------------------------------------------------------ #
        hfs = os.path.join(tmp, "vol800.hfs")
        if make_hfs(hfs, 800):
            is_image("HFS (800K, hformat)", hfs, "hfs")
            big = os.path.join(tmp, "vol20m.hfs")
            if make_hfs(big, 20 * 1024, "Bigger"):
                is_image("HFS (20 MB, hformat)", big, "hfs")
            # The signature alone must not be enough: deark requires the
            # allocation block size to be a nonzero multiple of 512, and
            # so does this.
            for bad, label in ((0, "zero"), (700, "not a multiple of 512")):
                p = os.path.join(tmp, "hfsbad%d.bin" % bad)
                spoiled = bytearray(open(hfs, "rb").read(65536))
                struct.pack_into(">I", spoiled, 1024 + 20, bad)
                open(p, "wb").write(bytes(spoiled))
                not_image("HFS with allocation block size %s" % label, p)
        else:
            skipped.append("HFS (no hformat; install hfsutils)")

        # ------------------------------------------------------ #
        # Apple Partition Map                                     #
        # ------------------------------------------------------ #
        apm = os.path.join(tmp, "disk.apm")
        make_apm(apm)
        is_image("Apple Partition Map", apm, "apm")
        # Both halves of "an entry in sector 1 AND in sector 2", and the
        # first of the two is the one that discriminates: the probe enters
        # this branch on the block at 1024, so spoiling THAT block only
        # tests that the branch is not entered (a mutation dropping the
        # 512 read passed until this case was written the other way up).
        for at, label in ((512, "no map entry in sector 1"),
                          (1024, "no map entry in sector 2")):
            p = os.path.join(tmp, "apmbad%d.bin" % at)
            raw = bytearray(open(apm, "rb").read())
            raw[at:at + 4] = bytes(4)
            open(p, "wb").write(bytes(raw))
            not_image("APM with %s" % label, p)

        # ------------------------------------------------------ #
        # HFS+ / HFSX — hand-built, no oracle (see the docstring) #
        # ------------------------------------------------------ #
        for sig in (b"H+", b"HX"):
            p = os.path.join(tmp, "hfsplus_%s.bin" % sig.decode())
            make_volume_header(p, sig)
            got = sniff(unclassic, p)
            check("%s volume header" % sig.decode(), got == "disk image",
                  "sniffed as %r" % got)
            # The corroboration is that an image is whole sectors.
            odd = os.path.join(tmp, "hfsplus_odd.bin")
            make_volume_header(odd, sig, size=4000)
            not_image("%s in a file that is not whole sectors"
                      % sig.decode(), odd)

        # ------------------------------------------------------ #
        # The corpus: nothing in it is a disk image               #
        # ------------------------------------------------------ #
        fixtures = os.path.join(ROOT, "fixtures")
        claimed, seen = [], 0
        for name in sorted(os.listdir(fixtures)) if os.path.isdir(fixtures) \
                else []:
            p = os.path.join(fixtures, name)
            if not os.path.isfile(p) or name.endswith(".md"):
                continue
            seen += 1
            if sniff(unclassic, p) == "disk image":
                claimed.append(name)
        if seen:
            check("corpus sweep (%d fixtures)" % seen, not claimed,
                  "claimed as disk images: %s" % ", ".join(claimed[:5]))
        else:
            skipped.append("corpus sweep (no fixtures)")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    for s in skipped:
        print("run_diskimage: skipped %s" % s)
    for p in problems:
        print("run_diskimage: %s" % p, file=sys.stderr)
    if problems:
        print("run_diskimage: FAILED (%d of %d)" % (len(problems), ran),
              file=sys.stderr)
        return 1
    print("run_diskimage: ok (%d checks)" % ran)
    return 0


if __name__ == "__main__":
    sys.exit(main())
