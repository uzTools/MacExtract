#!/usr/bin/env python3
"""gen_sit13_tables.py — mechanically transcribe the StuffIt method-13
fixed Huffman tables into src/sit13_tables.h. Run from the repo root;
the output is committed so the build does not depend on reference/
being populated.

No format facts are invented here: every value is parsed out of a
reference file. **Which one changed on 2026-09-20**: the tables are
printed in full in the format's own published description
(reference/notes/sit13_theunarchiver.md, "Tables"), so they no longer
come out of XADStuffIt13Handle.m. All 17 arrays were compared between
the two before the source was switched and are identical, and
regenerating from the page reproduces the committed header byte for
byte — which is the check that the switch changed nothing."""
import re, sys

SRC = "reference/notes/sit13_theunarchiver.md"
DST = "src/sit13_tables.h"


def parse_arrays(text):
    out = {}
    for m in re.finditer(
            r"static const int (\w+)\[(\d+)\]\s*=\s*\{(.*?)\};",
            text, re.S):
        name, size, body = m.group(1), int(m.group(2)), m.group(3)
        vals = [int(v, 0) for v in re.findall(r"-?(?:0x[0-9a-fA-F]+|\d+)", body)]
        assert len(vals) == size, (name, len(vals), size)
        out[name] = vals
    return out


def fmt(vals, per=16, hexfmt=False):
    lines = []
    for i in range(0, len(vals), per):
        chunk = vals[i:i + per]
        if hexfmt:
            lines.append("    " + ",".join("0x%03x" % v for v in chunk) + ",")
        else:
            lines.append("    " + ",".join("%2d" % v for v in chunk) + ",")
    return "\n".join(lines)


def main():
    arrays = parse_arrays(open(SRC).read())
    # The page names them "...TreeLengths_n" where the implementation
    # said "...CodeLengths_n"; same arrays, checked element by element
    # when the source was switched.
    for k in range(1, 6):
        for a, b in (("FirstTreeLengths_%d", "FirstCodeLengths_%d"),
                     ("SecondTreeLengths_%d", "SecondCodeLengths_%d"),
                     ("OffsetTreeLengths_%d", "OffsetCodeLengths_%d")):
            if (a % k) in arrays:
                arrays[b % k] = arrays[a % k]
    # The page gives the offset codes' SIZES by listing them in prose
    # ("11, 13, 14, 11, or 11 entires"); take them from the arrays
    # themselves, which is the same statement and cannot drift.
    arrays.setdefault("OffsetCodeSize",
                      [len(arrays["OffsetCodeLengths_%d" % k])
                       for k in range(1, 6)])
    need = (["FirstCodeLengths_%d" % i for i in range(1, 6)] +
            ["SecondCodeLengths_%d" % i for i in range(1, 6)] +
            ["OffsetCodeLengths_%d" % i for i in range(1, 6)] +
            ["OffsetCodeSize", "MetaCodes", "MetaCodeLengths"])
    for n in need:
        assert n in arrays, n

    with open(DST, "w") as f:
        f.write("""/*
 * sit13_tables.h — fixed Huffman tables for StuffIt method 13.
 *
 * GENERATED by tools/gen_sit13_tables.py from the format's own
 * published description, reference/notes/sit13_theunarchiver.md
 * (fetched by tools/fetch_references.sh), which prints these tables
 * in full. Do not edit by hand; regenerate instead.
 */
#ifndef UNC_SIT13_TABLES_H
#define UNC_SIT13_TABLES_H

#include <stdint.h>

""")
        for i in range(1, 6):
            for kind in ("First", "Second"):
                name = "%sCodeLengths_%d" % (kind, i)
                f.write("static const uint8_t sit13_%s[321] = {\n%s\n};\n\n"
                        % (name.lower(), fmt(arrays[name])))
            name = "OffsetCodeLengths_%d" % i
            vals = arrays[name]
            f.write("static const uint8_t sit13_%s[%d] = {\n%s\n};\n\n"
                    % (name.lower(), len(vals), fmt(vals)))
        f.write("static const uint8_t sit13_offsetcodesize[5] = { %s };\n\n"
                % ", ".join(str(v) for v in arrays["OffsetCodeSize"]))
        f.write("static const uint8_t *const sit13_firstlengths[5] = {\n")
        f.write("".join("    sit13_firstcodelengths_%d,\n" % i for i in range(1, 6)))
        f.write("};\n\nstatic const uint8_t *const sit13_secondlengths[5] = {\n")
        f.write("".join("    sit13_secondcodelengths_%d,\n" % i for i in range(1, 6)))
        f.write("};\n\nstatic const uint8_t *const sit13_offsetlengths[5] = {\n")
        f.write("".join("    sit13_offsetcodelengths_%d,\n" % i for i in range(1, 6)))
        f.write("};\n\n")
        f.write("/* Meta code used to serialize dynamic code lengths: value i\n"
                " * has LSB-first code sit13_metacodes[i] of length\n"
                " * sit13_metacodelengths[i]. */\n")
        f.write("static const uint16_t sit13_metacodes[37] = {\n%s\n};\n\n"
                % fmt(arrays["MetaCodes"], per=8, hexfmt=True))
        f.write("static const uint8_t sit13_metacodelengths[37] = {\n%s\n};\n\n"
                % fmt(arrays["MetaCodeLengths"]))
        f.write("#endif /* UNC_SIT13_TABLES_H */\n")
    print("wrote", DST)
    return 0


if __name__ == "__main__":
    sys.exit(main())
