#!/usr/bin/env python3
"""run_pak.py — ARC methods 0x0a (Crushed) and 0x0b (Distilled).

Both are PAK's, from NoGate Consulting, and PAK is the only program
that ever wrote them. So unlike every other suite here, the archives
under test cannot be generated by anything on this machine: they come
from PAK 2.51 itself, run under DOSBox by tools/pak.py, or from the two
real specimens in the corpus.

What grades the output, in the order the evidence is worth having:

  1. The CRC-16 PAK stored per member, over the DECODED bytes. It was
     written by the 1990 compressor, so it is the one check that no
     decoder here can influence — including ours. `macextract t` fails
     the entry if it disagrees.
  2. For generated archives, the bytes that went in.
  3. deark for 0x0b and `unar` for 0x0a, where they are installed —
     two independent implementations, and NOT interchangeable:
     deark does not implement Crushed at all, and `unar` decodes
     Distilled WRONG (BLOCKERS.md), which is why it is never consulted
     about method 11 here.

That last point is the reason this file exists rather than a few more
cases in run_arc.py: the obvious oracle for this format is the wrong
one, and a suite that reached for it would have graded a correct
decoder as broken and a broken one as correct.
"""
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pak                                          # noqa: E402

CRUSHED, DISTILLED = 0x0A, 0x0B
DEARK = os.path.join(ROOT, "build", "deark", "deark")


def deark_bin():
    """deark, building it once if `reference/` has it and `build/` does not.

    `ci.sh` runs `make clean`, which takes `build/` and every oracle in it
    (TESTING.md says the same of `macunpack`). For this format that would
    quietly drop method 0x0b to CRC-only grading on every CI run, so the
    build is triggered from here rather than left to the operator."""
    if os.path.exists(DEARK):
        return DEARK
    script = os.path.join(ROOT, "tools", "build_deark.sh")
    if os.path.isdir(os.path.join(ROOT, "reference", "deark")):
        subprocess.run(["sh", script], capture_output=True, timeout=1800)
        if os.path.exists(DEARK):
            return DEARK
    return shutil.which("deark")


def extract_us(macextract, archive, out):
    return subprocess.run([macextract, "x", "-o", out, archive],
                          capture_output=True)


def read(path):
    return open(path, "rb").read() if os.path.exists(path) else None


def check_archive(macextract, archive, want, problems):
    """want: {member name: bytes} for what the archive should hold, or
    {} when the archive is a real specimen and only its own CRCs and the
    second implementations can say."""
    base = os.path.basename(archive)
    listed = pak.members(archive)
    methods = {m for m, _n, _c, _s in listed}
    if not (methods & {CRUSHED, DISTILLED}):
        problems.append("%s: holds no 0x0a/0x0b member" % base)
        return

    # 1. The archive's own CRCs.
    r = subprocess.run([macextract, "t", archive], capture_output=True)
    if r.returncode != 0:
        problems.append("%s: `macextract t` exited %d: %s"
                        % (base, r.returncode,
                           r.stderr.decode("utf-8", "replace").strip()[:200]))

    out = tempfile.mkdtemp()
    try:
        extract_us(macextract, archive, out)
        ours = {}
        for _m, name, _c, _s in listed:
            got = read(os.path.join(out, name))
            if got is None:
                problems.append("%s: we did not write %s" % (base, name))
                continue
            ours[name] = got

        # 2. The bytes that went in.
        for name, blob in want.items():
            if name in ours and ours[name] != blob:
                problems.append("%s: %s came back %d bytes, wanted %d"
                                % (base, name, len(ours[name]), len(blob)))

        # 3. The second implementations, each on the method it can read.
        if DISTILLED in methods and deark_bin():
            dk = tempfile.mkdtemp()
            try:
                subprocess.run([deark_bin(), "-od", dk, "-o", "m", archive],
                               capture_output=True, timeout=600)
                for i, (m, name, _c, _s) in enumerate(listed):
                    if m != DISTILLED or name not in ours:
                        continue
                    got = read(os.path.join(dk, "m.%03d.%s" % (i, name)))
                    if got is None:
                        problems.append("%s: deark wrote nothing for %s"
                                        % (base, name))
                    elif got != ours[name]:
                        problems.append("%s: %s differs from deark" % (base, name))
            finally:
                shutil.rmtree(dk, ignore_errors=True)

        if CRUSHED in methods and shutil.which("unar"):
            ud = tempfile.mkdtemp()
            try:
                subprocess.run(["unar", "-q", "-f", "-o", ud, archive],
                               capture_output=True, timeout=600)
                for m, name, _c, _s in listed:
                    if m != CRUSHED or name not in ours:
                        continue
                    got = read(os.path.join(ud, name))
                    if got is None:
                        sub = os.path.splitext(os.path.basename(archive))[0]
                        got = read(os.path.join(ud, sub, name))
                    if got is None:
                        problems.append("%s: unar wrote nothing for %s"
                                        % (base, name))
                    elif got != ours[name]:
                        problems.append("%s: %s differs from unar" % (base, name))
            finally:
                shutil.rmtree(ud, ignore_errors=True)
    finally:
        shutil.rmtree(out, ignore_errors=True)


def damage(macextract, archive, problems):
    """The rule run_arc.py and run_robustness.py use: a damaged archive
    may refuse, but it may not die by signal or exit outside 0..2, which
    is what turns a sanitizer abort into a reported failure. Crushed
    reads a 13-bit code and uses it as a subscript, and its replacement
    scan can point a parent at its own descendant, so this is the net
    under the two loops that could run away."""
    blob = open(archive, "rb").read()
    variants = []
    for cut in (1, 2, 3, 5, 8, 13, 21, 34):
        if len(blob) > cut:
            variants.append(("trunc%d" % cut, blob[:-cut]))
    step = max(1, len(blob) // 12)
    for at in range(0, len(blob), step):
        b = bytearray(blob)
        b[at] ^= 0xFF
        variants.append(("flip%d" % at, bytes(b)))

    tmp = tempfile.mkdtemp()
    try:
        for tag, payload in variants:
            bad = os.path.join(tmp, "dmg-%s" % tag)
            open(bad, "wb").write(payload)
            out = tempfile.mkdtemp()
            try:
                r = subprocess.run([macextract, "x", "-o", out, bad],
                                   capture_output=True, timeout=300)
                if r.returncode < 0 or r.returncode > 2:
                    problems.append("%s %s: exit %d"
                                    % (os.path.basename(archive), tag,
                                       r.returncode))
            except subprocess.TimeoutExpired:
                problems.append("%s %s: timed out" % (os.path.basename(archive), tag))
            finally:
                shutil.rmtree(out, ignore_errors=True)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def real_specimens():
    """The .pak files in the corpus, if the corpus is present."""
    fix = os.path.join(ROOT, "fixtures")
    out = []
    for name in ("arc2pak1.pak", "derived-INTRECHO.pak"):
        p = os.path.join(fix, name)
        if os.path.exists(p):
            out.append(p)
    return out


def main():
    macextract = os.path.join(ROOT, "build", "macextract")
    args = sys.argv[1:]
    if "--macextract" in args:
        macextract = args[args.index("--macextract") + 1]
    if not os.path.exists(macextract):
        print("run_pak: no CLI at %s" % macextract)
        return 1

    corpus = os.path.join(pak.HOME, "corpus")
    generated = sorted(f for f in os.listdir(corpus)
                       if f.endswith(".pak")) if os.path.isdir(corpus) else []
    if not generated and pak.have_pak():
        pak.make(corpus)
        generated = sorted(f for f in os.listdir(corpus) if f.endswith(".pak"))

    specimens = real_specimens()
    if not generated and not specimens:
        print("run_pak: SKIPPED — no PAK corpus (tools/pak.py --setup --make) "
              "and no .pak fixtures")
        return 0

    problems, ran = [], 0
    inputs = {}
    ind = os.path.join(corpus, "input")
    if os.path.isdir(ind):
        for f in os.listdir(ind):
            inputs[f] = open(os.path.join(ind, f), "rb").read()

    for f in generated:
        p = os.path.join(corpus, f)
        listed = pak.members(p)
        want = {n: inputs[n] for _m, n, _c, _s in listed if n in inputs}
        check_archive(macextract, p, want, problems)
        ran += 1
    for p in specimens:
        check_archive(macextract, p, {}, problems)
        ran += 1

    # Damage only the small ones: the point is the decoder's loops, and
    # a 300 KB archive multiplied by 20 variants buys nothing but time.
    for p in [os.path.join(corpus, f) for f in generated] + specimens:
        if os.path.getsize(p) < 120000:
            damage(macextract, p, problems)

    if problems:
        for p in problems[:40]:
            print("run_pak: " + p)
        print("run_pak: FAILED (%d problem(s) over %d archive(s))"
              % (len(problems), ran))
        return 1
    extra = []
    if not deark_bin():
        extra.append("no deark, so method 11 was graded by CRC only")
    if not shutil.which("unar"):
        extra.append("no unar, so method 10 was graded by CRC only")
    print("run_pak: OK (%d archive(s))%s"
          % (ran, (" — " + "; ".join(extra)) if extra else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
