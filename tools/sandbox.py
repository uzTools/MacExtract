#!/usr/bin/env python3
"""sandbox.py — run code this project did not write, confined.

    sandbox.py --selftest
    sandbox.py [--ro HOST:INSIDE]... [--rw HOST:INSIDE] [--cwd DIR] -- ARGV...

Some graders are other people's readers of a format (reference/applebackup:
a gist, a parser generated by Kaitai Struct). They are run, never trusted:
each goes into a box made with unprivileged Linux namespaces (unshare(1)),
which this machine allows and which needs nothing installed:

  - a user namespace: "root" inside is this user outside, nothing more;
  - an empty network namespace: no interface but a loopback that is down;
  - its own mount namespace, whose root is a fresh tmpfs holding only /usr
    (read-only; /bin, /lib and /lib64 are links into it on this system),
    /dev/null, a scratch /tmp, and the directories given: --ro read-only,
    one --rw; the root itself is read-only once they are in place. Not
    $HOME, not the repository, not /tmp, not /proc of the host;
  - its own PID, IPC and UTS namespaces: it sees and signals only itself;
  - limits: CPU seconds, address space, file size, processes, and a wall
    clock (`timeout`, outside the box).

What it CANNOT stop: a kernel bug reachable from an unprivileged process —
there is no seccomp filter — and anything the code does with what it was
given read-only, or writes into the --rw directory (whose contents the
caller reads as untrusted data, as every grader here does).

--selftest is the evidence: from inside the box it tries the network, the
home directory, the repository, a write beside its output, a read-only
input and the host's processes, and fails unless every one is refused and
the output directory alone is writable.
"""
import argparse, os, shlex, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

LIMITS = "ulimit -t 120; ulimit -v 2000000; ulimit -f 4000000; ulimit -p 64"


def command(argv, ro=(), rw=None, cwd="/"):
    """The argv that runs `argv` in the box. `ro` and `rw` are
    (host path, path inside) pairs; paths inside are absolute."""
    sh = ["set -e",
          'R="$(mktemp -d)"',
          'mount -t tmpfs -o mode=755,nosuid sandbox "$R"',
          'mkdir -p "$R/usr" "$R/dev" "$R/proc" "$R/tmp"',
          'mount --rbind /usr "$R/usr"',
          'mount -o remount,bind,ro,nosuid "$R/usr"',
          'for l in bin lib lib64 sbin; do ln -s usr/$l "$R/$l"; done',
          'touch "$R/dev/null"',
          'mount --bind /dev/null "$R/dev/null"']
    binds = [(h, i, True) for h, i in ro] + ([(rw[0], rw[1], False)]
                                             if rw else [])
    for host, inside, readonly in binds:
        t = '"$R"' + shlex.quote(inside)
        kind = "d" if os.path.isdir(host) else "f"
        sh.append(f'mkdir -p {t}' if kind == "d"
                  else f'mkdir -p "$(dirname {t})" && touch {t}')
        sh.append(f'mount --bind {shlex.quote(os.path.abspath(host))} {t}')
        if readonly:
            sh.append(f'mount -o remount,bind,ro,nosuid,nodev {t}')
    sh += ['mount -t proc proc "$R/proc"',
           # Scratch the code may need, then the root itself read-only:
           # nothing written outside --rw survives, nor can be written.
           'mount -t tmpfs -o size=64m,nosuid,nodev sandbox-tmp "$R/tmp"',
           'mount -o remount,ro,bind "$R"',
           LIMITS,
           'cd "$R"',
           # No mount of the old root survives: chroot into the new one,
           # with an environment of our own and nothing of the caller's.
           f'exec /usr/sbin/chroot "$R" /usr/bin/env -i PATH=/usr/bin HOME=/tmp '
           f'LANG=C.UTF-8 sh -c {shlex.quote("cd " + shlex.quote(cwd) + " && exec " + " ".join(shlex.quote(a) for a in argv))}']
    return ["unshare", "--user", "--map-root-user", "--mount", "--net",
            "--pid", "--fork", "--ipc", "--uts", "--mount-proc",
            "sh", "-c", "\n".join(sh)]


def run(argv, ro=(), rw=None, cwd="/", timeout=300, **kw):
    return subprocess.run(["timeout", "--kill-after=5", str(timeout)] +
                          command(argv, ro, rw, cwd), **kw)


PROBE = r'''
import os, socket, sys
out = []
def tried(what, fn):
    try:
        fn()
        out.append(f"ALLOWED {what}")
    except Exception as e:
        out.append(f"refused {what}: {type(e).__name__}")
def net():
    s = socket.create_connection(("1.1.1.1", 80), timeout=3)
def net_dns():
    socket.getaddrinfo("github.com", 443)
def read(p):
    return lambda: open(p, "rb").read(1)
def write(p):
    def f():
        with open(p, "w") as h: h.write("x")
    return f
def listdir(p):
    return lambda: os.listdir(p) or (_ for _ in ()).throw(FileNotFoundError(p))
tried("network to 1.1.1.1", net)
tried("name lookup", net_dns)
tried("the home directory", listdir(sys.argv[1]))
tried("the repository", read(sys.argv[2]))
tried("a write beside the output", write("/in/../escape"))
tried("a write to the read-only input", write("/in/probe-input"))
tried("a write to /usr", write("/usr/escape"))
def procs():
    # Inside its own PID namespace the box sees itself: sh and python.
    pids = [p for p in os.listdir("/proc") if p.isdigit()]
    if len(pids) <= 4:
        raise PermissionError(f"{len(pids)} processes visible")
tried("the host's processes", procs)
tried("a write to the output", write("/out/ok"))
print("\n".join(out))
'''


def selftest():
    with tempfile.TemporaryDirectory(dir=os.path.join(ROOT, ".tmp")) as t:
        indir, outdir = os.path.join(t, "in"), os.path.join(t, "out")
        os.makedirs(indir)
        os.makedirs(outdir)
        with open(os.path.join(indir, "probe.py"), "w") as f:
            f.write(PROBE)
        with open(os.path.join(indir, "probe-input"), "w") as f:
            f.write("input\n")
        r = run(["python3", "-I", "/in/probe.py", os.path.expanduser("~"),
                 os.path.join(ROOT, "CLAUDE.md")],
                ro=[(indir, "/in")], rw=(outdir, "/out"), cwd="/out",
                timeout=60, capture_output=True, text=True)
        print(r.stdout, end="")
        if r.returncode:
            print(r.stderr[-800:])
            print("sandbox: the probe did not run")
            return 1
        lines = r.stdout.splitlines()
        want_allowed = {"a write to the output"}
        bad = [l for l in lines
               if (l.startswith("ALLOWED") and
                   l[len("ALLOWED "):] not in want_allowed) or
               (l.startswith("refused") and
                l.split(":")[0][len("refused "):] in want_allowed)]
        escaped = os.path.exists(os.path.join(t, "escape"))
        intact = open(os.path.join(indir, "probe-input")).read() == "input\n"
        if bad or escaped or not intact or len(lines) != 9:
            print("sandbox: FAILED —", bad, "escape file" if escaped else "",
                  "" if intact else "input changed")
            return 1
        print("sandbox: every probe refused but the output directory")
        return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--ro", action="append", default=[])
    ap.add_argument("--rw")
    ap.add_argument("--cwd", default="/")
    ap.add_argument("argv", nargs="*")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    ro = [tuple(x.split(":", 1)) for x in a.ro]
    rw = tuple(a.rw.split(":", 1)) if a.rw else None
    return run(a.argv, ro, rw, a.cwd).returncode


if __name__ == "__main__":
    sys.exit(main())
