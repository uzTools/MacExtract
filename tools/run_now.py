#!/usr/bin/env python3
"""run_now.py — Now Compress extraction, adjudicated by `unar`.

The corpus holds ONE Now Compress archive: a single file, a single fork,
and blocks of two of the five shapes the format has. So the archives
here are generated by tools/synth_now.py — every block shape, a folder
tree, both forks, several files in one archive, the dictionary cache
carried from one file's stream into the next, and a block table whose
offsets are wrong by a constant — and each is required to agree THREE
ways:

  1. the bytes that went into the generator;
  2. what `unar` extracts, XADNowCompressHandle being the reference
     fmt_now.c was transcribed from;
  3. what our CLI extracts.

Point 2 is what makes the generated archives worth anything. A
generator written from the same reading as the decoder round-trips
whatever that reading is, right or wrong — twice in M13 exactly that
happened, and only the oracle noticed (DECISIONS.md 2026-08-15).

What it cannot do is check the READING against the format: for the
three shapes no fixture reaches, XADMaster is the only implementation
in existence, so agreement here means the transcription matches its
source, not that its source is right. The two shapes the corpus fixture
does reach are graded against a real archive by the differential suite.

One archive is deliberately graded ONE way, because the two
implementations disagree and the reference is wrong: an empty file
anywhere but last (see check_empty_stream).
"""
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.join(os.path.dirname(__file__), "..")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import synth_now                                     # noqa: E402
from make_manifests import parse_appledouble         # noqa: E402


def run(cmd):
    return subprocess.run(cmd, capture_output=True)


def forks(root, path, who):
    """(data, rsrc) as the extractor wrote them. A missing file is an
    empty fork — the convention both `unar` and this CLI use, and the
    reason a fork ONLY has to be present when it has bytes: `unar`
    writes no data file at all for an entry the archive gives no data
    fork."""
    full = os.path.join(root, path)
    data = open(full, "rb").read() if os.path.isfile(full) else b""
    if who == "us":
        side = full + ".rsrc"
        rsrc = open(side, "rb").read() if os.path.isfile(side) else b""
        return data, rsrc, None, None
    head, tail = os.path.split(full)
    side = os.path.join(head, "._" + tail)
    if not os.path.isfile(side):
        return data, b"", None, None
    rsrc, typ, creator = parse_appledouble(side)
    return data, rsrc or b"", typ, creator


def command(who, unclassic, archive, out):
    if who == "unar":
        return ["unar", "-q", "-f", "-nr", "-D", "-k", "hidden", "-o", out,
                archive]
    return [unclassic, "x", "-o", out, archive]


def extract_and_compare(who, unclassic, archive, want, problems):
    """Run one extractor and compare everything it wrote. Returns its
    exit status, which the caller judges: usually it must be 0."""
    name = os.path.basename(archive)
    out = tempfile.mkdtemp()
    try:
        r = run(command(who, unclassic, archive, out))
        for path, content in sorted(want.items()):
            if content is None:
                if not os.path.isdir(os.path.join(out, path)):
                    problems.append("%s: %s made no folder %r"
                                    % (name, who, path))
                continue
            wdata, wrsrc = content
            data, rsrc, _, _ = forks(out, path, who)
            for fork, got, wanted in (("data", data, wdata),
                                      ("rsrc", rsrc, wrsrc)):
                if got == wanted:
                    continue
                if len(got) != len(wanted):
                    problems.append("%s: %s wrote %d %s bytes for %r, "
                                    "wanted %d" % (name, who, len(got), fork,
                                                   path, len(wanted)))
                else:
                    at = next(i for i, (a, b) in enumerate(zip(got, wanted))
                              if a != b)
                    problems.append("%s: %s wrote the right length but the "
                                    "wrong bytes for %r (%s fork, first at "
                                    "%d)" % (name, who, path, fork, at))
        return r
    finally:
        shutil.rmtree(out, ignore_errors=True)


def check(archive, want, unclassic, problems):
    """`want` is path -> (data, rsrc), or None for a folder."""
    name = os.path.basename(archive)
    for who in ("unar", "us"):
        r = extract_and_compare(who, unclassic, archive, want, problems)
        if r.returncode != 0:
            problems.append("%s: %s exited %d (%s)"
                            % (name, who, r.returncode,
                               r.stdout.decode("utf-8", "replace").strip()
                               .replace("\n", " | ")[-160:]))


def check_metadata(archive, unclassic, problems):
    """Type and creator, which the fork comparison cannot see. Ours comes
    from `l -v`; the oracle's from the Finder info in its AppleDouble
    sidecar, which it writes only for an entry that has a resource
    fork."""
    name = os.path.basename(archive)
    r = run([unclassic, "l", "-v", archive])
    listed = {}
    for line in r.stdout.decode("mac-roman").splitlines()[1:]:
        parts = line.split(None, 4)
        if len(parts) == 5 and parts[0] == "f":
            listed[parts[4]] = parts[3]
    if "Folder/two forks" not in listed:
        problems.append("%s: our own listing lost 'Folder/two forks'" % name)
    elif listed["Folder/two forks"] != "APPL/NCdc":
        problems.append("%s: we list 'Folder/two forks' as %s, not APPL/NCdc"
                        % (name, listed["Folder/two forks"]))

    out = tempfile.mkdtemp()
    try:
        run(["unar", "-q", "-f", "-nr", "-D", "-k", "hidden", "-o", out,
             archive])
        _, _, typ, creator = forks(out, "Folder/two forks", "unar")
        if (typ, creator) != ("APPL", "NCdc"):
            problems.append("%s: the oracle read type/creator as %r/%r"
                            % (name, typ, creator))
    finally:
        shutil.rmtree(out, ignore_errors=True)


def check_refusals(tmp, unclassic, problems):
    """Two mutations, both of which must be noticed. Without them the
    suite could only ever report success — a comparison nothing has been
    shown to fail is not evidence (CLAUDE.md)."""
    src = os.path.join(tmp, "synth-now-stored.now")
    blob = bytearray(open(src, "rb").read())

    # 1. A byte of a stored block's payload. Nothing in the format
    #    checksums a block, so this must come out as WRONG BYTES rather
    #    than as an error — which is what proves the byte comparison
    #    above is live rather than vacuous.
    at = blob.find(b"Now Compress was Now")
    if at < 0:
        problems.append("stored payload not found; the mutation proof "
                        "cannot run")
        return
    flipped = bytearray(blob)
    flipped[at] ^= 0x20
    bad = os.path.join(tmp, "flipped.now")
    open(bad, "wb").write(bytes(flipped))
    out = tempfile.mkdtemp()
    try:
        run([unclassic, "x", "-o", out, bad])
        got = open(os.path.join(out, "text"), "rb").read()
        if got == synth_now.sample_data()["text"]:
            problems.append("flipped.now: a flipped payload byte changed "
                            "nothing in the output")
    finally:
        shutil.rmtree(out, ignore_errors=True)

    # 2. A byte of the first block TABLE, which the format does
    #    checksum. It must be refused, not decoded into rubbish.
    # The first entry's `datastart` field is where its block table is.
    table = int.from_bytes(blob[24 + 98:24 + 102], "big")
    broken = bytearray(blob)
    broken[table + 9] ^= 0x11              # inside the first record
    bad = os.path.join(tmp, "broken.now")
    open(bad, "wb").write(bytes(broken))
    out = tempfile.mkdtemp()
    try:
        r = run([unclassic, "x", "-o", out, bad])
        if r.returncode == 0:
            problems.append("broken.now: a damaged block table was accepted")
        u = run(["unar", "-q", "-f", "-nr", "-D", "-o", out, bad])
        if u.returncode == 0:
            problems.append("broken.now: the oracle accepted a damaged "
                            "block table, so the mutation proves nothing")
    finally:
        shutil.rmtree(out, ignore_errors=True)


def check_empty_stream(tmp, unclassic, problems):
    """A zero-length file in the middle of an archive: the one shape
    where the two implementations disagree, and where WE are right.

    The oracle's block loop tests "have I run out of blocks?" once
    rather than until it is true, so a stream with no blocks at all
    leaves the previous file's first block in place and the file AFTER
    the empty one is decoded at a stale offset (synth_now.py). This
    reader opens one stream per file and never notices.

    Asserted rather than described, both halves: our extraction must be
    byte-exact, and the oracle must still fail. If a later `unar` fixes
    it, this says so instead of quietly agreeing.
    """
    archive, want = synth_now.write_empty_stream(tmp)
    r = extract_and_compare("us", unclassic, archive, want, problems)
    if r.returncode != 0:
        problems.append("synth-now-empty.now: we exited %d on an empty file "
                        "in the middle" % r.returncode)
    out = tempfile.mkdtemp()
    try:
        u = run(command("unar", unclassic, archive, out))
    finally:
        shutil.rmtree(out, ignore_errors=True)
    if u.returncode == 0:
        problems.append("synth-now-empty.now: the oracle now reads an empty "
                        "stream in the middle — the divergence recorded in "
                        "synth_now.py and TESTING.md is out of date")


# The second real Now Compress archive, found on 2026-08-16 (DECISIONS.md).
# `unar` cannot decode ANY of its forks — the format's bit streams end
# wherever they end, and 129 of its 306 blocks leave fewer than 7 spare
# bits, which is the overrun measured the day before — so its manifest
# carries names, type and creator and marks every fork unadjudicated.
# These hashes are therefore NOT ground truth. They are a regression
# anchor for output no oracle in existence can grade, and they sit beside
# a check that CAN fail on its own terms: the resource fork has to be a
# resource fork.
REAL_FIXTURE = "derived-SyntheticReferences2.0.sea"
REAL_FORKS = {
    "Synthetic References v2.0/SynRef2.0 INFO": (
        "7044bbb8fde9e5f52b1b61a5184d2cc29e4b46b8c8a1d55b8c8eae525bfc7472",
        "473a97ba6d88b40e02b2f40b63591562a138f9ff8836fd7bd7b56158a5342428"),
    "Synthetic References v2.0/Synthetic References v.2.0": (
        "f680a0e92759a05cae094a0de2a75e7023c0e7296e02552779be462042542dc0",
        None),
}


def check_real_fixture(unclassic, problems):
    """The corpus's second real archive, if it has been fetched."""
    import hashlib
    import struct
    archive = os.path.join(ROOT, "fixtures", REAL_FIXTURE)
    if not os.path.exists(archive):
        print("run_now: %s absent, skipping the real-archive checks"
              % REAL_FIXTURE)
        return 0
    out = tempfile.mkdtemp()
    try:
        r = run([unclassic, "x", "--forks", "hidden", "-o", out, archive])
        if r.returncode != 0:
            problems.append("%s: we exited %d" % (REAL_FIXTURE, r.returncode))
        for path, (dhash, rhash) in REAL_FORKS.items():
            full = os.path.join(out, path)
            head, tail = os.path.split(full)
            got = {"data": full, "rsrc": os.path.join(head, "._" + tail)}
            for fork, want in (("data", dhash), ("rsrc", rhash)):
                if want is None:
                    continue
                if not os.path.isfile(got[fork]):
                    problems.append("%s: no %s fork for %r"
                                    % (REAL_FIXTURE, fork, path))
                    continue
                blob = open(got[fork], "rb").read()
                if hashlib.sha256(blob).hexdigest() != want:
                    problems.append("%s: the %s fork of %r changed"
                                    % (REAL_FIXTURE, fork, path))

        # The one check here that owes nothing to a previous run of ours:
        # a resource fork describes itself in its first 16 bytes — data
        # offset, map offset, data length, map length — and those four
        # numbers have to account for exactly the bytes we produced. A
        # wrong decode does not survive this.
        rsrc = os.path.join(out, "Synthetic References v2.0",
                            "._SynRef2.0 INFO")
        if os.path.isfile(rsrc):
            blob = open(rsrc, "rb").read()
            doff, moff, dlen, mlen = struct.unpack(">IIII", blob[:16])
            if doff + dlen != moff or moff + mlen != len(blob):
                problems.append("%s: the resource fork we produced is not a "
                                "resource fork (%d+%d != %d, or %d+%d != %d)"
                                % (REAL_FIXTURE, doff, dlen, moff, moff, mlen,
                                   len(blob)))
    finally:
        shutil.rmtree(out, ignore_errors=True)
    return 1


def check_encoder_specimens(unclassic, problems):
    """Archives written by Now Compress itself, if they have been made.

    `tools/vmac/nowcompress.py` drives Now QuickFiler 5.0.1 under Mini
    vMac and leaves its specimens beside the emulator. They are not
    fixtures — the application is commercial and is not redistributed —
    so this checks them when they are there and says so when they are
    not. What they cover that nothing else can: the block shapes as the
    ORIGINAL encoder writes them, against the bytes that went in.
    """
    home = os.environ.get("UNC_VMAC_HOME") or os.path.join(
        os.environ.get("XDG_CACHE_HOME", os.path.expanduser("~/.cache")),
        "unclassic", "vmac")
    root = os.path.join(home, "specimens", "now")
    if not os.path.isdir(root):
        print("run_now: no encoder specimens (tools/vmac/nowcompress.py) — "
              "skipping the from-the-encoder checks")
        return 0
    ran = 0
    for case in sorted(os.listdir(root)):
        d = os.path.join(root, case)
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            if not f.endswith(".dat"):
                continue
            archive = os.path.join(d, f)
            r = run([unclassic, "l", archive])
            if b"Now Compress" not in r.stdout + r.stderr:
                continue          # an uncompressed file the encoder declined
            out = tempfile.mkdtemp()
            try:
                x = run([unclassic, "x", "-o", out, archive])
                if x.returncode != 0:
                    problems.append("%s/%s: we exited %d" % (case, f,
                                                             x.returncode))
                for root_, _, names in os.walk(out):
                    for name in names:
                        want = os.path.join(d, "in-" + name)
                        if not os.path.exists(want):
                            continue
                        got = open(os.path.join(root_, name), "rb").read()
                        if got != open(want, "rb").read():
                            problems.append("%s/%s: %r is not what was "
                                            "compressed" % (case, f, name))
                ran += 1
            finally:
                shutil.rmtree(out, ignore_errors=True)
    print("run_now: %d specimen(s) from the encoder checked" % ran)
    return ran


def main():
    unclassic = os.path.join(ROOT, "build", "unclassic")
    args = sys.argv[1:]
    if "--unclassic" in args:
        unclassic = args[args.index("--unclassic") + 1]
    if not os.path.exists(unclassic):
        print("run_now: no CLI at %s" % unclassic)
        return 1
    if shutil.which("unar") is None:
        print("run_now: SKIPPED — no `unar` to adjudicate with")
        return 0

    problems = []
    tmp = tempfile.mkdtemp()
    ran = 0
    try:
        made = synth_now.write_all(tmp)
        for archive in sorted(made):
            check(archive, made[archive], unclassic, problems)
            ran += 1
        check_metadata(os.path.join(tmp, "synth-now-tree.now"), unclassic,
                       problems)
        check_refusals(tmp, unclassic, problems)
        check_empty_stream(tmp, unclassic, problems)
        ran += 3
        ran += check_real_fixture(unclassic, problems)
        ran += check_encoder_specimens(unclassic, problems)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    for p in problems:
        print("NOW FAIL " + p)
    print("now: %d archive(s) checked, %d problem(s)" % (ran, len(problems)))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
