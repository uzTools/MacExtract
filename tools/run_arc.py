#!/usr/bin/env python3
"""run_arc.py — ARC extraction, adjudicated by `unar`.

The corpus has no `.arc` (measured 2026-08-15 by innermost format over
all 805 fixtures), so the archives here are generated by
tools/synth_arc.py — one per compression method, plus one holding every
method at once — and each is required to agree THREE ways:

  1. the bytes that went into the generator;
  2. what `unar` extracts (XADARCParser and its handles are the
     reference fmt_arc.c was transcribed from, so this is the check
     that a transcription error cannot survive);
  3. what our CLI extracts.

Point 2 is not a formality. The first version of the crunch decoder read
its 12-bit codes LSB-first, and because the generator mirrored the same
mistake the round trip was perfect and the CRC — which is computed over
the DECODED bytes — agreed. Only `unar` disagreed. The same shape caught
the compress encoder widening its codes one step early.

If Debian's `arc` binary is present (tools/get_arc.sh fetches it), real
archives from a real encoder are checked too, which is what covers
methods 2/4/8/9 with bytes nothing here produced. Its absence is
reported, never silent.
"""
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.join(os.path.dirname(__file__), "..")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import synth_arc                                    # noqa: E402

# Absolute: this is run with cwd set elsewhere, and a relative
# program path would then resolve against THAT directory.
ARC_BIN = os.path.abspath(os.path.join(ROOT, "build", "arc", "usr",
                                       "bin", "arc"))


def extracted(outdir, name):
    """unar drops multi-entry archives into a subdirectory of its own."""
    direct = os.path.join(outdir, name)
    if os.path.exists(direct):
        return open(direct, "rb").read()
    for sub in os.listdir(outdir):
        p = os.path.join(outdir, sub, name)
        if os.path.exists(p):
            return open(p, "rb").read()
    return None


def run(cmd):
    return subprocess.run(cmd, capture_output=True)


def check(archive, want, macextract, problems):
    for who, cmd in (("unar", ["unar", "-q", "-f", "-o", None, archive]),
                     ("us", [macextract, "x", "-o", None, archive])):
        out = tempfile.mkdtemp()
        try:
            r = run([c if c is not None else out for c in cmd])
            for name, content in want.items():
                got = extracted(out, name)
                if got is None:
                    problems.append("%s: %s did not write %s"
                                    % (os.path.basename(archive), who, name))
                elif got != content:
                    problems.append("%s: %s wrote %d bytes for %s, wanted %d"
                                    % (os.path.basename(archive), who,
                                       len(got), name, len(content)))
            if r.returncode != 0:
                problems.append("%s: %s exited %d"
                                % (os.path.basename(archive), who, r.returncode))
        finally:
            shutil.rmtree(out, ignore_errors=True)


def main():
    macextract = os.path.join(ROOT, "build", "macextract")
    args = sys.argv[1:]
    if "--macextract" in args:
        macextract = args[args.index("--macextract") + 1]
    if not os.path.exists(macextract):
        print("run_arc: no CLI at %s" % macextract)
        return 1
    if shutil.which("unar") is None:
        print("run_arc: SKIPPED — no `unar` to adjudicate with")
        return 0

    problems = []
    tmp = tempfile.mkdtemp()
    ran = 0
    try:
        subprocess.run([sys.executable,
                        os.path.join(ROOT, "tools", "synth_arc.py"), tmp],
                       capture_output=True, check=True)
        data = synth_arc.sample_data()
        for f in sorted(os.listdir(tmp)):
            if not f.endswith(".arc"):
                continue
            if "mixed" in f:
                want = {"m%d.bin" % m: data["text.txt"] for m in range(1, 10)}
            else:
                want = data
            check(os.path.join(tmp, f), want, macextract, problems)
            ran += 1

        # Damage every generated archive, systematically.
        #
        # ARC is the thinnest-graded format here: the corpus has ONE ARC
        # fixture, so `run_robustness.sh` gives the whole format ten
        # variants, and until 2026-08-24 the only other damaged input was
        # the single flipped byte below. That is a poor net under decoders
        # whose tables are indexed by a code read straight from the
        # stream — crunch reads 12 bits and uses them as an array
        # subscript — so this sweeps truncations and bit flips across
        # every method the generator writes.
        #
        # WHAT IS ASSERTED is only what can be: not that a damaged archive
        # fails, because a flip can land in a byte nothing checks, but
        # that the extractor exits 0..2 (never by signal), and that when
        # it does return success every file it wrote is byte-for-byte
        # ours. The suite runs under ASan+UBSan in ci.sh, and the exit
        # rule is what turns a sanitizer abort into a reported failure
        # rather than an ordinary refusal.
        for f in sorted(os.listdir(tmp)):
            if not f.endswith(".arc") or f == "damaged.arc":
                continue
            blob = open(os.path.join(tmp, f), "rb").read()
            variants = []
            for cut in (1, 2, 3, 5, 8, 13, 21, 34):
                if len(blob) > cut:
                    variants.append(("trunc%d" % cut, blob[:-cut]))
            for at in range(0, len(blob), max(1, len(blob) // 12)):
                b = bytearray(blob)
                b[at] ^= 0xFF
                variants.append(("flip%d" % at, bytes(b)))
            for tag, payload in variants:
                bad = os.path.join(tmp, "dmg-%s-%s" % (tag, f))
                open(bad, "wb").write(payload)
                out = tempfile.mkdtemp()
                try:
                    r = run([macextract, "x", "-o", out, bad])
                    # The SAME rule run_robustness.py uses, and for the
                    # same reason: a non-zero exit is fine (the archive is
                    # damaged), but death by signal or an exit outside
                    # 0..2 is a sanitizer abort or a crash, and those are
                    # what this exists to find. Checking only "did it
                    # write wrong bytes" would have let an ASan trip pass
                    # as an ordinary refusal — which it did, in the first
                    # draft of this sweep.
                    if r.returncode < 0 or r.returncode > 2:
                        problems.append("%s: exit %d"
                                        % (os.path.basename(bad),
                                           r.returncode))
                    if r.returncode == 0:
                        # Accepted: then every file it wrote must be one
                        # of ours, byte for byte. A damaged archive that
                        # "succeeds" with different bytes is the failure
                        # this is looking for.
                        for name, content in data.items():
                            got = extracted(out, name)
                            if got is not None and got != content:
                                problems.append(
                                    "%s: accepted, but %s came out wrong"
                                    % (os.path.basename(bad), name))
                finally:
                    shutil.rmtree(out, ignore_errors=True)
                ran += 1

        # A per-entry CRC failure must stay per-entry: the entry after a
        # damaged one still comes out.
        one = os.path.join(tmp, "synth-arc-m2.arc")
        blob = bytearray(open(one, "rb").read())
        blob[0x20] ^= 0x01
        bad = os.path.join(tmp, "damaged.arc")
        open(bad, "wb").write(bytes(blob))
        out = tempfile.mkdtemp()
        r = run([macextract, "x", "-o", out, bad])
        if r.returncode == 0:
            problems.append("damaged.arc: a flipped payload byte was accepted")
        if extracted(out, "tiny.txt") != data["tiny.txt"]:
            problems.append("damaged.arc: a later entry was lost with the "
                            "damaged one")
        shutil.rmtree(out, ignore_errors=True)
        ran += 1

        # Real archives from a real encoder, if it is here.
        if os.path.exists(ARC_BIN):
            src = tempfile.mkdtemp()
            for name, content in data.items():
                open(os.path.join(src, name), "wb").write(content)
            # 8.3, because `arc` silently truncates the archive's own
            # basename to it — "real-crunched.arc" is written as
            # "real-cru.arc", and the check then looks for a file that
            # was never going to exist.
            for flags, label in (("a", "rcrun"), ("aq", "rsqua"),
                                 ("as", "rstor")):
                arch = os.path.abspath(os.path.join(tmp, "%s.arc" % label))
                subprocess.run([ARC_BIN, flags, arch] + sorted(data),
                               cwd=src, capture_output=True)
                if os.path.exists(arch):
                    check(arch, data, macextract, problems)
                    ran += 1
                else:
                    problems.append("%s.arc: arc wrote nothing" % label)
            shutil.rmtree(src, ignore_errors=True)
        else:
            print("run_arc: no `arc` encoder (tools/get_arc.sh) — the "
                  "generated archives still cover methods 1-9")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    for p in problems:
        print("ARC FAIL " + p)
    print("arc: %d archive(s) checked, %d problem(s)" % (ran, len(problems)))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
