#!/usr/bin/env python3
"""gen_sit6_tables.py — derive the StuffIt method-6 fixed decode tree from
reference/macutils/macunpack/sit.c into src/sit6_tables.h. Run from the repo
root; the output is committed so the build does not depend on reference/
being populated.

Method 6 ("fixed Huffman") codes every segment with a tree whose SHAPE is
the same for every archive: macunpack builds it once per fork from the
constant weight table code6[258] by repeatedly splitting the leaf range at
half the remaining weight (sit_dosplit). Only the BYTE each leaf stands for
is re-declared per segment. Since the shape depends on nothing but a
constant, it is computed here rather than on a 68000.

No format facts are invented: code6 is parsed out of the LGPL reference file
(see NOTICE) and the split below is a transcription of sit_dosplit.

Usage: tools/gen_sit6_tables.py
"""
import re, sys

SRC = "reference/macutils/macunpack/sit.c"
DST = "src/sit6_tables.h"

LEAVES = 258            # nodelist[1..258]; 257 and 258 are the terminator
NODES = 515             # 258 leaves + 257 internal nodes, root at index 0
INTERNAL = NODES - LEAVES   # 257: the root plus nodelist[259..514]


def parse_code6(text):
    m = re.search(r"static short code6\[258\]\s*=\s*\{(.*?)\};", text, re.S)
    assert m, "code6[] not found in " + SRC
    vals = [int(v) for v in re.findall(r"-?\d+", m.group(1))]
    assert len(vals) == LEAVES, len(vals)
    return vals


def build_tree(code6):
    """Transcription of sit_dosplit, with the recursion turned into an
    explicit stack (the engine forbids recursion; this generator does not
    need it either). Leaf node indices are 1..258, internal ones 0 and
    259..514, exactly as macunpack numbers them."""
    zero = [0] * NODES
    one = [0] * NODES
    nodeptr = LEAVES                    # sit_nodeptr
    stack = [(0, sum(code6), 1, LEAVES)]
    while stack:
        ptr, total, low, upp = stack.pop()
        half = total // 2
        locsum, i = 0, low
        while locsum < half:
            locsum += code6[i - 1]
            i += 1
        if low == i - 1:
            zero[ptr] = low
        else:
            nodeptr += 1
            zero[ptr] = nodeptr
            stack.append((nodeptr, half, low, i - 1))
        if upp == i:
            one[ptr] = upp
        else:
            nodeptr += 1
            one[ptr] = nodeptr
            stack.append((nodeptr, half, i, upp))
    return zero, one, nodeptr


def selftest(zero, one, used):
    """A tree that agrees only with itself proves nothing: check it is a
    tree, that every leaf is reachable exactly once, and that no internal
    node dangles."""
    seen = {}
    depth = 0
    stack = [(0, 0)]
    while stack:
        n, d = stack.pop()
        assert n not in seen, "node %d reached twice" % n
        seen[n] = d
        if 1 <= n <= LEAVES:
            depth = max(depth, d)
            continue
        assert n == 0 or n > LEAVES, n
        assert zero[n] and one[n], "internal node %d has no children" % n
        stack.append((zero[n], d + 1))
        stack.append((one[n], d + 1))
    leaves = [n for n in seen if 1 <= n <= LEAVES]
    assert len(leaves) == LEAVES, len(leaves)
    assert used == NODES - 1, used
    return depth


def fmt(vals, per=12):
    return "\n".join("    " + ",".join("%3d" % v for v in vals[i:i + per]) + ","
                     for i in range(0, len(vals), per))


def compact(vals):
    """Only the root and nodelist[259..514] have children, so drop the 258
    all-zero leaf rows: row 0 is the root, row k is macunpack's node
    258 + k. Child values keep macunpack's numbering (1..258 leaf ordinal,
    259.. internal), so the decoder indexes with child - SIT6_LEAVES."""
    out = [vals[0]] + vals[LEAVES + 1:]
    assert len(out) == INTERNAL, len(out)
    return out


def main():
    code6 = parse_code6(open(SRC).read())
    zero, one, used = build_tree(code6)
    depth = selftest(zero, one, used)

    with open(DST, "w") as f:
        f.write("""/*
 * sit6_tables.h — the fixed decode tree for StuffIt method 6.
 *
 * GENERATED by tools/gen_sit6_tables.py from
 * reference/macutils/macunpack/sit.c (code6[258] + sit_dosplit) — LGPL,
 * see NOTICE. Do not edit by hand; regenerate instead.
 *
 * Row 0 is the root and row k is macunpack's internal node %d + k; a bit
 * takes sit6_zero[row] or sit6_one[row]. A child value <= %d is a LEAF and
 * the value is the ordinal of a byte the segment declares (ordinals %d and
 * %d are the end-of-segment terminator); a larger value is the internal
 * node in row value - %d. Tree depth is %d bits, so a walk always ends.
 */
#ifndef UNC_SIT6_TABLES_H
#define UNC_SIT6_TABLES_H

#include <stdint.h>

#define SIT6_LEAVES   %d
#define SIT6_INTERNAL %d
#define SIT6_DEPTH    %d

""" % (LEAVES, LEAVES, LEAVES - 1, LEAVES, LEAVES, depth,
       LEAVES, INTERNAL, depth))
        f.write("static const uint16_t sit6_zero[SIT6_INTERNAL] = {\n%s\n};\n\n"
                % fmt(compact(zero)))
        f.write("static const uint16_t sit6_one[SIT6_INTERNAL] = {\n%s\n};\n\n"
                % fmt(compact(one)))
        f.write("#endif /* UNC_SIT6_TABLES_H */\n")
    print("wrote %s (depth %d, %d nodes)" % (DST, depth, used + 1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
