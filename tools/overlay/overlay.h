/* The SpaceSaver overlay — a DECODER rather than a cipher, and the first
 * proof that a decoder can be one at all. It is 'OVLY' 129: a separate
 * resource from the ciphers, because an encrypted zip has no reason to load
 * a SpaceSaver decoder or the other way round. */
/* On `overlay-eager` all six images live in ONE resource, 'OVLY' 128, read
 * once at launch (tools/overlay/mkbundle.py). The per-image ids below are
 * then indexes INTO that bundle rather than resource numbers; on
 * `selective-loading` they are the resource numbers themselves. */
#define OVL_ID_BUNDLE        128
#define OVL_ID_CRYPT         128
#define OVL_ID_SPACESAVER    129
#define OVL_ID_CPTDD         130   /* Compact Pro and DiskDoubler together:
                                    * fmt_dd calls fmt_cpt's RLE and LZH
                                    * forks, so splitting them would mean an
                                    * overlay calling into another overlay */
#define OVL_ID_LZH           131
#define OVL_ID_ARC           132
#define OVL_ID_NOW           133
#define OVL_ID_SUPERDISK     134
#define OVL_ID_PACKIT        135
#define OVL_ID_TEXT          136   /* MIME and the text envelopes together:
                                    * a MIME part may be base64 or uuencoded,
                                    * so the decoder calls into both and an
                                    * overlay cannot call another overlay */
#define OVL_ID_STUFFIT       137
#define OVL_ID_EXO           138   /* zip, gzip, Unix compress, tar — and
                                    * zlib, which nothing else calls      */
#define OVL_ID_CODECS        139   /* the shared machinery, which patches
                                    * itself into the host vector         */
/* BinHex and btoa stand alone: only MIME calls into uu and base64, so only
 * those three have to travel together. Splitting these two out means opening
 * a .hqx loads ~3 KB rather than the 15,864 B the whole text group cost —
 * which is the difference between a decoder that fits a small machine and one
 * that does not. Measured by nm over the objects, not assumed. */
#define OVL_ID_BINHEX        140
#define OVL_ID_DART          142   /* DART: the decoder only. Its header
                                   * reader is also its probe, so that half
                                   * stays resident and is compiled into
                                   * this image as well — the same
                                   * arrangement SpaceSaver has.        */
#define OVL_ID_BTOA          141   /* btoa/atob, which nothing calls into
                                    * and which calls nothing            */

