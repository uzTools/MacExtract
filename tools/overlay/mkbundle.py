#!/usr/bin/env python3
"""mkbundle.py — the six overlay images as ONE resource.

`selective-loading` carries one `OVLY` per format and loads whichever the
archive turns out to need. That costs a disk access AFTER the archive has been
chosen, and on a Mac Plus with one drive the application's own floppy may have
been swapped by then (BRANCH_NOTES.md on either branch).

This branch trades the other way: **one read at launch, while the boot disk is
certainly still in**, and then everything the archive cannot want is thrown
away before the engine asks for memory. One resource rather than six because
six `GetResource` calls are six reads, and the whole point of loading eagerly
is to pay for the disk once.

Layout — chosen so the shim can find an image without a parser:

    +0  uint16  count
    +2  uint16  reserved (0)
    +4  per entry, count of them, 12 bytes each:
            uint16 id        the OVL_ID_* the image answers to
            uint16 pad
            uint32 offset    from the start of the resource
            uint32 length
        then the images, each aligned to 4.

All big-endian, which is both the 68000's order and this project's rule about
byte-wise reads.

    tools/overlay/mkbundle.py out.r  OVL_ID_CRYPT:image.bin  OVL_ID_LZH:...

Ids are NAMES, resolved from overlay.h by tools/overlay/ovlid.py: the
directory this writes is what the shim searches with the OVL_ID_* constants,
so a number written here would be a second copy of that table, and a
disagreement between the two is a run-time miss rather than a build error.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ovlid


def main():
    if len(sys.argv) < 3:
        print(__doc__.strip().split("\n")[-1], file=sys.stderr)
        return 2
    out = sys.argv[1]
    items = []
    for arg in sys.argv[2:]:
        sid, path = arg.split(":", 1)
        with open(path, "rb") as f:
            items.append((ovlid.resolve(sid), f.read()))
    items.sort()

    head = 4 + 12 * len(items)
    off = head
    dir_bytes, body = b"", b""
    for sid, img in items:
        pad = (-len(img)) % 4
        dir_bytes += struct.pack(">HHII", sid, 0, off, len(img))
        body += img + b"\0" * pad
        off += len(img) + pad
    blob = struct.pack(">HH", len(items), 0) + dir_bytes + body

    with open(out, "w") as f:
        f.write("/* GENERATED by tools/overlay/mkbundle.py — do not edit. */\n")
        f.write('data \'OVLY\' (%d, "overlay bundle") {\n'
                % ovlid.resolve("OVL_ID_BUNDLE"))
        hexed = blob.hex()
        for i in range(0, len(hexed), 64):
            f.write('    $"%s"\n' % hexed[i:i + 64])
        f.write("};\n")
    print("mkbundle: %s — %d image(s), %d B" % (out, len(items), len(blob)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
